export const V3C_COPY: Record<V3cLang, V3cCopy> = { en: EN, it: IT, de: DE, es: ES, fr: FR, nl: NL, pl: PL, pt: PT, ru: RU, sv: SV, tr: TR };

/** La lingua del sito (localStorage «agentic-lang»: it/en/es/fr/ru…) → la copy. Lingue sconosciute leggono l'inglese. */
export function copyFor(lang: string | null | undefined): V3cCopy {
  return V3C_COPY[v3cLang(lang)];
}

/** Per F10: le chiavi foglia del dizionario, in ordine, così la lista in docs si rigenera e non si scrive a mano. */
export function copyKeys(obj: Record<string, unknown> = EN as unknown as Record<string, unknown>, prefix = ""): string[] {
  const out: string[] = [];
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object" && !Array.isArray(v)) out.push(...copyKeys(v as Record<string, unknown>, key));
    else out.push(key);
  }
  return out;
}
