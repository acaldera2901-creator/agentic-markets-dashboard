/** Le 11 lingue del sito (F10: tutte complete). */
export const V3C_LANGS = ["en", "it", "de", "es", "fr", "nl", "pl", "pt", "ru", "sv", "tr"] as const;
export type V3cLang = (typeof V3C_LANGS)[number];

/** La lingua salvata («it», «de-AT», «PT»…) → una delle 11; tutto il resto → «en». */
export function v3cLang(lang: string | null | undefined): V3cLang {
  const code = (lang ?? "").toLowerCase().slice(0, 2);
  return (V3C_LANGS as readonly string[]).includes(code) ? (code as V3cLang) : "en";
}

const V3C_LOCALES: Record<V3cLang, string> = {
  en: "en-GB", it: "it-IT", de: "de-DE", es: "es-ES", fr: "fr-FR", nl: "nl-NL",
  pl: "pl-PL", pt: "pt-PT", ru: "ru-RU", sv: "sv-SE", tr: "tr-TR",
};

/** Il locale Intl per date e numeri nella lingua del visitatore. */
export function v3cLocale(lang: string | null | undefined): string {
  return V3C_LOCALES[v3cLang(lang)];
}

