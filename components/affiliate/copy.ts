export type AffLang = "it" | "en";

export function affLang(lang: string | undefined | null): AffLang {
  return (lang ?? "").slice(0, 2).toLowerCase() === "it" ? "it" : "en";
}

/** Sostituisce {chiave} nel testo. Una chiave assente resta com'è (si vede, non si inventa). */
export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

